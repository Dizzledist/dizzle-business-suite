import { test, expect } from '@playwright/test';

test.beforeEach(async ({ request }) => {
  expect((await request.post('/api/demo/reset', { headers: { 'X-Demo-Identity': 'manager' }, data: {} })).ok()).toBeTruthy();
});

test('marketing creates content and creative; owner reviews and publishes; only the selected rep can retrieve it', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Test identity').selectOption('marketing');
  await expect(page.getByRole('heading', { name: 'Make the next release count.' })).toBeVisible();
  await page.getByRole('tab', { name: 'Calendar', exact: true }).click();
  const campaign = page.locator('.planner-form').first();
  await campaign.getByRole('combobox', { name: 'Brand', exact: true }).selectOption('cheddr');
  await campaign.getByLabel('Campaign title').fill('Browser launch');
  await campaign.getByLabel('Objective').fill('Preview the collection');
  await campaign.getByRole('button', { name: 'Create campaign' }).click();
  await expect(page.getByRole('status')).toHaveText('Campaign created.');
  const content = page.locator('.content-form');
  await content.getByLabel('Title', { exact: true }).fill('Launch announcement');
  await content.getByLabel('Objective').fill('Introduce the collection');
  await content.getByLabel('Destination account').fill('@cheddr-demo');
  await content.getByLabel('Planned date and time (Pacific)').fill('2026-11-18T11:00');
  await content.getByLabel('Caption or brief').fill('Discover the autumn collection.');
  await content.getByRole('combobox', { name: 'Approved linked creative' }).selectOption({ label: 'Cheddr autumn campaign image · v1' });
  await content.getByRole('button', { name: 'Create draft' }).click();
  const item = page.locator('.calendar-item').filter({ hasText: 'Launch announcement' });
  await expect(item).toContainText('11:00 AM');
  await item.getByRole('button', { name: 'Submit review' }).click();
  await page.getByRole('tab', { name: 'Image Studio' }).click();
  await page.getByLabel('Image prompt').fill('Crimson autumn launch');
  await page.getByLabel('Original Cheddr logo reference').check();
  await page.getByLabel('Simulate one transient sample error').check();
  await page.getByRole('button', { name: 'Generate sample artwork' }).click();
  const job = page.locator('.generation-card').first();
  await expect(job).toContainText('failed');
  await job.getByRole('button', { name: 'Retry job' }).click();
  await expect(job.locator('img')).toBeVisible();
  const [draftDownload] = await Promise.all([page.waitForEvent('download'), job.getByRole('button', { name: 'Download sample-artwork-v1.svg' }).click()]);
  expect(draftDownload.suggestedFilename()).toBe('sample-artwork-v1.svg');
  const editor = { 'X-Demo-Identity': 'marketing' };
  const workspace = await (await page.request.get('/api/marketing/workspace', { headers: editor })).json();
  const generated = workspace.generationJobs[0];
  expect((await page.request.post(`/api/marketing/versions/${generated.versionId}/publish`, { headers: { 'X-Demo-Identity': 'owner' }, data: { audienceMode: 'all', repIds: [] } })).status()).toBe(409);
  await job.getByRole('button', { name: 'Submit version for review' }).click();
  await page.getByLabel('Test identity').selectOption('owner');
  await page.getByLabel('Department', { exact: true }).selectOption('marketing');
  await page.getByRole('tab', { name: 'Review', exact: true }).click();
  await page.getByLabel('Reviewer notes').fill('Approved exact content and creative.');
  await page.locator('.review-row').filter({ hasText: 'Launch announcement' }).getByRole('button', { name: 'Approve', exact: true }).click();
  await page.getByRole('button', { name: 'Approve version', exact: true }).click();
  await page.getByRole('tab', { name: 'Calendar', exact: true }).click();
  await page.locator('.calendar-item').filter({ hasText: 'Launch announcement' }).getByRole('button', { name: 'Schedule internally' }).click();
  await expect(page.locator('.calendar-item').filter({ hasText: 'Launch announcement' })).toContainText('scheduled');
  await page.getByRole('tab', { name: 'Assets', exact: true }).click();
  const asset = page.locator('.asset-record').filter({ hasText: 'Creative · Cheddr autumn launch' });
  await asset.getByRole('combobox').selectOption('selected');
  await asset.getByLabel('Rep A · Juniper accounts').check();
  await asset.getByRole('button', { name: 'Publish approved version' }).click();
  await expect(asset.locator('.publication-row')).toContainText('Selected: rep-a');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/marketing-assets-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Test identity').selectOption('rep-a');
  await page.getByLabel('Find Assets').fill('Creative · Cheddr');
  const salesAsset = page.locator('.sales-asset-row');
  await expect(salesAsset).toHaveCount(1);
  await expect(salesAsset.locator('img')).toBeVisible();
  const [download] = await Promise.all([page.waitForEvent('download'), salesAsset.getByRole('button', { name: /Download/ }).click()]);
  expect(download.suggestedFilename()).toBe('sample-artwork-v1.svg');
  const file = `/api/assets/${generated.assetId}/versions/${generated.versionId}/file`;
  expect((await page.request.get(file, { headers: { 'X-Demo-Identity': 'rep-b' } })).status()).toBe(404);
  await page.getByLabel('Test identity').selectOption('rep-b');
  await page.getByLabel('Find Assets').fill('Creative · Cheddr');
  await expect(page.locator('.sales-asset-row')).toHaveCount(0);
  await page.getByLabel('Test identity').selectOption('owner');
  await page.getByLabel('Department', { exact: true }).selectOption('marketing');
  await page.getByRole('tab', { name: 'Assets', exact: true }).click();
  await page.locator('.asset-record').filter({ hasText: 'Creative · Cheddr autumn launch' }).getByRole('button', { name: 'Retire', exact: true }).click();
  expect((await page.request.get(file, { headers: { 'X-Demo-Identity': 'rep-a' } })).status()).toBe(404);
});

test('mobile filters, protected document previews, and recoverable workspace error', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByLabel('Test identity').selectOption('marketing');
  await expect(page.getByRole('heading', { name: 'Make the next release count.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/marketing-home-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.getByLabel('Brand filter').selectOption('frosty');
  await expect(page.getByText('Nothing scheduled yet.')).toBeVisible();
  await page.getByRole('tab', { name: 'Calendar', exact: true }).click();
  await expect(page.getByText('No content matches these filters.')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/marketing-calendar-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Brand filter').selectOption('all');
  await page.getByLabel('Channel filter').selectOption('SMS');
  await expect(page.getByText('No content matches these filters.')).toBeVisible();
  await page.getByLabel('Channel filter').selectOption('all');
  await page.getByLabel('Status filter').selectOption('scheduled');
  await expect(page.locator('.calendar-item')).toHaveCount(1);
  await page.getByLabel('Test identity').selectOption('rep-a');
  await page.getByLabel('Find Assets').fill('BATCH-26-044');
  await expect(page.locator('.sales-asset-row')).toHaveCount(1);
  await page.getByText('Preview document', { exact: true }).click();
  await expect(page.locator('.document-preview pre')).toContainText('not a laboratory result');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.route('**/api/marketing/workspace', route => route.fulfill({ status: 403, json: { error: 'Marketing access denied for this demo.' } }));
  await page.getByLabel('Test identity').selectOption('marketing');
  await expect(page.getByRole('alert')).toContainText('Marketing access denied');
  await page.unroute('**/api/marketing/workspace');
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Make the next release count.' })).toBeVisible();
});
